@_silgen_name("sandbox_init")
private func c_sandbox_init(
  _ profile: UnsafePointer<CChar>,
  _ flags: UInt64,
  _ errorbuf: UnsafeMutablePointer<UnsafeMutablePointer<CChar>?>?
) -> Int32

private func enterReadOnlyContainSandbox() -> Bool {
  // Kernel-level Seatbelt containment: deny all IPv4/IPv6 network traffic (outbound and inbound)
  // and deny all subprocess execution, while allowing local Mach/IPC needed by Apple Vision.framework.
  let profile = "(version 1)(allow default)(deny network-inbound)(deny network-outbound (remote ip))(deny process-exec*)"
  var errBuf: UnsafeMutablePointer<CChar>? = nil
  let rc = profile.withCString { ptr in
    c_sandbox_init(ptr, 0, &errBuf)
  }
  return rc == 0
}

let isKernelSandboxed = enterReadOnlyContainSandbox()

let concealedTypeNames: Set<String> = [
  "org.nspasteboard.ConcealedType",
  "org.nspasteboard.TransientType",
  "org.nspasteboard.AutoGeneratedType",
  "com.agilebits.onepassword",
  "com.typeit4me.clipping",
  "de.petermaurer.TransientPasteboardType",
]

struct WindowMetadata: Codable {
  let frontmostApp: String?
  let bundleId: String?
  let windowTitle: String?
}

struct ClipboardOutput: Codable {
  let changeCount: Int
  let skippedConcealed: Bool
  let concealedTypes: [String]
  let text: String?
  let frontmostApp: String?
  let windowTitle: String?
}

struct OcrOutput: Codable {
  let text: String
  let lineCount: Int
  let lines: [String]
  let frontmostApp: String?
  let windowTitle: String?
}

struct FocusedTextOutput: Codable {
  let trusted: Bool
  let skippedSecure: Bool
  let role: String?
  let text: String?
  let frontmostApp: String?
  let windowTitle: String?
}

struct KeyWatchOutput: Codable {
  let listenAccess: Bool
  let skippedSecure: Bool
  let keyCount: Int
  let text: String
  let frontmostApp: String?
  let windowTitle: String?
}

struct PermissionsOutput: Codable {
  let appName: String
  let bundleId: String
  let executablePath: String
  let kernelNetworkAndExecSandboxed: Bool
  let accessibilityTrusted: Bool
  let inputMonitoringAccess: Bool
  let screenCaptureAccess: Bool
  let readOnlyContained: Bool
}

func handlePermissions(prompt: Bool) {
  let axTrusted: Bool
  if prompt {
    let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
    axTrusted = AXIsProcessTrustedWithOptions(opts)
  } else {
    axTrusted = AXIsProcessTrusted()
  }
  let listenAccess = prompt ? CGRequestListenEventAccess() : CGPreflightListenEventAccess()
  let screenAccess = prompt ? CGRequestScreenCaptureAccess() : CGPreflightScreenCaptureAccess()
  let bundle = Bundle.main
  let appName = (bundle.object(forInfoDictionaryKey: "CFBundleDisplayName") as? String)
    ?? (bundle.object(forInfoDictionaryKey: "CFBundleName") as? String)
    ?? "Gadget Read-Only Sensory Capture"
  let bundleId = bundle.bundleIdentifier ?? "local.gadget.sensory-capture"
  let execPath = bundle.executablePath ?? CommandLine.arguments[0]

  printJson(
    PermissionsOutput(
      appName: appName,
      bundleId: bundleId,
      executablePath: execPath,
      kernelNetworkAndExecSandboxed: isKernelSandboxed,
      accessibilityTrusted: axTrusted,
      inputMonitoringAccess: listenAccess,
      screenCaptureAccess: screenAccess,
      readOnlyContained: true
    )
  )
}

func inspectFocusedElement() -> (trusted: Bool, isSecure: Bool, role: String?, value: String?) {
  let trusted = AXIsProcessTrusted()
  guard trusted else {
    return (false, false, nil, nil)
  }
  let sys = AXUIElementCreateSystemWide()
  var focusedRef: CFTypeRef?
  let err = AXUIElementCopyAttributeValue(sys, kAXFocusedUIElementAttribute as CFString, &focusedRef)
  guard err == .success, let elemRef = focusedRef else {
    return (true, false, nil, nil)
  }
  let elem = elemRef as! AXUIElement

  var roleRef: CFTypeRef?
  AXUIElementCopyAttributeValue(elem, kAXRoleAttribute as CFString, &roleRef)
  let role = roleRef as? String

  var subroleRef: CFTypeRef?
  AXUIElementCopyAttributeValue(elem, kAXSubroleAttribute as CFString, &subroleRef)
  let subrole = subroleRef as? String

  if role == "AXSecureTextField" || subrole == "AXSecureTextField" {
    return (true, true, role ?? subrole, nil)
  }

  var valRef: CFTypeRef?
  if AXUIElementCopyAttributeValue(elem, kAXValueAttribute as CFString, &valRef) == .success,
     let str = valRef as? String, !str.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
    let clipped = str.count > 4000 ? String(str.suffix(4000)) : str
    return (true, false, role, clipped)
  }
  return (true, false, role, nil)
}

func handleFocusedText() {
  let win = currentWindowMetadata()
  let info = inspectFocusedElement()
  printJson(
    FocusedTextOutput(
      trusted: info.trusted,
      skippedSecure: info.isSecure,
      role: info.role,
      text: info.value,
      frontmostApp: win.frontmostApp,
      windowTitle: win.windowTitle
    )
  )
}

final class KeyCaptureBuffer {
  var chars: String = ""
  var keyCount: Int = 0
  var skippedSecure: Bool = false
}

func handleWatchKeys(durationSec: Double) {
  let win = currentWindowMetadata()
  let hasAccess = CGPreflightListenEventAccess()
  guard hasAccess else {
    printJson(
      KeyWatchOutput(
        listenAccess: false,
        skippedSecure: false,
        keyCount: 0,
        text: "",
        frontmostApp: win.frontmostApp,
        windowTitle: win.windowTitle
      )
    )
    return
  }

  let buffer = KeyCaptureBuffer()
  let mask = CGEventMask(1 << CGEventType.keyDown.rawValue)
  let ptr = Unmanaged.passUnretained(buffer).toOpaque()

  guard let tap = CGEvent.tapCreate(
    tap: .cgSessionEventTap,
    place: .headInsertEventTap,
    options: .listenOnly,
    eventsOfInterest: mask,
    callback: { _, type, event, userInfo in
      guard type == .keyDown, let userInfo = userInfo else {
        return Unmanaged.passUnretained(event)
      }
      let buf = Unmanaged<KeyCaptureBuffer>.fromOpaque(userInfo).takeUnretainedValue()
      let focus = inspectFocusedElement()
      if focus.isSecure {
        buf.skippedSecure = true
        return Unmanaged.passUnretained(event)
      }
      let flags = event.flags
      if flags.contains(.maskCommand) || flags.contains(.maskControl) {
        return Unmanaged.passUnretained(event)
      }
      var length = 0
      var chars = [UniChar](repeating: 0, count: 16)
      event.keyboardGetUnicodeString(maxStringLength: 16, actualStringLength: &length, unicodeString: &chars)
      if length > 0 {
        let s = String(utf16CodeUnits: chars, count: length)
        for ch in s {
          if ch == "\u{8}" || ch == "\u{7f}" {
            if !buf.chars.isEmpty { buf.chars.removeLast() }
          } else if ch == "\r" {
            buf.chars.append("\n")
            buf.keyCount += 1
          } else if !ch.isNewline && ch.asciiValue != nil && ch.asciiValue! < 32 {
            continue
          } else {
            buf.chars.append(ch)
            buf.keyCount += 1
          }
        }
      }
      return Unmanaged.passUnretained(event)
    },
    userInfo: ptr
  ) else {
    printJson(
      KeyWatchOutput(
        listenAccess: false,
        skippedSecure: false,
        keyCount: 0,
        text: "",
        frontmostApp: win.frontmostApp,
        windowTitle: win.windowTitle
      )
    )
    return
  }

  let source = CFMachPortCreateRunLoopSource(kCFAllocatorDefault, tap, 0)
  CFRunLoopAddSource(CFRunLoopGetCurrent(), source, .defaultMode)
  CGEvent.tapEnable(tap: tap, enable: true)
  CFRunLoopRunInMode(.defaultMode, max(0.05, min(durationSec, 30.0)), false)
  CGEvent.tapEnable(tap: tap, enable: false)

  let endWin = currentWindowMetadata()
  printJson(
    KeyWatchOutput(
      listenAccess: true,
      skippedSecure: buffer.skippedSecure,
      keyCount: buffer.keyCount,
      text: buffer.chars,
      frontmostApp: endWin.frontmostApp ?? win.frontmostApp,
      windowTitle: endWin.windowTitle ?? win.windowTitle
    )
  )
}

func currentWindowMetadata() -> WindowMetadata {
  let frontApp = NSWorkspace.shared.frontmostApplication
  let appName = frontApp?.localizedName
  let bundleId = frontApp?.bundleIdentifier
  let pid = frontApp?.processIdentifier ?? -1

  var foundTitle: String? = nil
  if let windowList = CGWindowListCopyWindowInfo([.optionOnScreenOnly, .excludeDesktopElements], kCGNullWindowID) as? [[String: Any]] {
    for entry in windowList {
      let ownerPid = entry[kCGWindowOwnerPID as String] as? Int32 ?? -2
      let layer = entry[kCGWindowLayer as String] as? Int ?? 0
      if layer == 0 && (pid == -1 || ownerPid == pid) {
        if let name = entry[kCGWindowName as String] as? String, !name.isEmpty {
          foundTitle = name
          break
        }
      }
    }
  }
  return WindowMetadata(frontmostApp: appName, bundleId: bundleId, windowTitle: foundTitle)
}

func printJson<T: Encodable>(_ value: T) {
  let encoder = JSONEncoder()
  if let data = try? encoder.encode(value), let str = String(data: data, encoding: .utf8) {
    print(str)
  } else {
    fputs("Failed to encode JSON\n", stderr)
    exit(1)
  }
}

func handleClipboard() {
  let pb = NSPasteboard.general
  let changeCount = pb.changeCount
  let rawTypes = (pb.types ?? []).map { $0.rawValue }
  let matchedConcealed = rawTypes.filter { t in
    if concealedTypeNames.contains(t) { return true }
    let lower = t.lowercased()
    return lower.contains("concealed") || lower.contains("onepassword") || lower.contains("transient")
  }
  let win = currentWindowMetadata()
  if !matchedConcealed.isEmpty {
    printJson(
      ClipboardOutput(
        changeCount: changeCount,
        skippedConcealed: true,
        concealedTypes: matchedConcealed,
        text: nil,
        frontmostApp: win.frontmostApp,
        windowTitle: win.windowTitle
      )
    )
    return
  }
  let text = pb.string(forType: .string)
  printJson(
    ClipboardOutput(
      changeCount: changeCount,
      skippedConcealed: false,
      concealedTypes: [],
      text: text,
      frontmostApp: win.frontmostApp,
      windowTitle: win.windowTitle
    )
  )
}

func handleOcr(imagePath: String) {
  let url = URL(fileURLWithPath: imagePath)
  guard let imageSource = CGImageSourceCreateWithURL(url as CFURL, nil),
        let cgImage = CGImageSourceCreateImageAtIndex(imageSource, 0, nil)
  else {
    fputs("Failed to load image at \(imagePath)\n", stderr)
    exit(2)
  }

  var recognizedLines: [String] = []
  let request = VNRecognizeTextRequest { req, err in
    if let err = err {
      fputs("Vision error: \(err.localizedDescription)\n", stderr)
      return
    }
    guard let observations = req.results as? [VNRecognizedTextObservation] else { return }
    for obs in observations {
      if let top = obs.topCandidates(1).first {
        let trimmed = top.string.trimmingCharacters(in: .whitespacesAndNewlines)
        if !trimmed.isEmpty {
          recognizedLines.append(trimmed)
        }
      }
    }
  }
  request.recognitionLevel = .accurate
  request.usesLanguageCorrection = true

  let handler = VNImageRequestHandler(cgImage: cgImage, options: [:])
  do {
    try handler.perform([request])
  } catch {
    fputs("Vision perform failed: \(error.localizedDescription)\n", stderr)
    exit(3)
  }

  let win = currentWindowMetadata()
  printJson(
    OcrOutput(
      text: recognizedLines.joined(separator: "\n"),
      lineCount: recognizedLines.count,
      lines: recognizedLines,
      frontmostApp: win.frontmostApp,
      windowTitle: win.windowTitle
    )
  )
}

func handleRenderTextImage(outPath: String, text: String) {
  let width = 1000
  let height = 320
  let size = NSSize(width: width, height: height)
  let image = NSImage(size: size)
  image.lockFocus()
  NSColor.white.setFill()
  NSBezierPath.fill(NSRect(origin: .zero, size: size))

  let paragraph = NSMutableParagraphStyle()
  paragraph.alignment = .left
  let attrs: [NSAttributedString.Key: Any] = [
    .font: NSFont.monospacedSystemFont(ofSize: 28, weight: .bold),
    .foregroundColor: NSColor.black,
    .paragraphStyle: paragraph,
  ]
  let attributed = NSAttributedString(string: text, attributes: attrs)
  attributed.draw(in: NSRect(x: 40, y: 40, width: width - 80, height: height - 80))
  image.unlockFocus()

  guard let tiffData = image.tiffRepresentation,
        let bitmap = NSBitmapImageRep(data: tiffData),
        let pngData = bitmap.representation(using: .png, properties: [:])
  else {
    fputs("Failed to render PNG\n", stderr)
    exit(4)
  }

  do {
    try pngData.write(to: URL(fileURLWithPath: outPath))
    print("{\"ok\":true,\"path\":\(String(data: try JSONEncoder().encode(outPath), encoding: .utf8)!)}")
  } catch {
    fputs("Failed to write PNG: \(error.localizedDescription)\n", stderr)
    exit(5)
  }
}

let args = CommandLine.arguments
guard args.count >= 2 else {
  fputs("Usage: GadgetSensoryCapture <permissions [--prompt]|clipboard|window-info|focused-text|watch-keys [sec]|ocr <imgPath>|render-text-image <outPath> <text>>\n", stderr)
  exit(1)
}

switch args[1] {
case "permissions":
  let prompt = args.contains("--prompt")
  handlePermissions(prompt: prompt)
case "clipboard":
  handleClipboard()
case "window-info":
  printJson(currentWindowMetadata())
case "focused-text":
  handleFocusedText()
case "watch-keys":
  let sec = args.count >= 3 ? (Double(args[2]) ?? 1.0) : 1.0
  handleWatchKeys(durationSec: sec)
case "ocr":
  guard args.count >= 3 else {
    fputs("Usage: gadget-sensory ocr <imgPath>\n", stderr)
    exit(1)
  }
  handleOcr(imagePath: args[2])
case "render-text-image":
  guard args.count >= 4 else {
    fputs("Usage: gadget-sensory render-text-image <outPath> <text>\n", stderr)
    exit(1)
  }
  handleRenderTextImage(outPath: args[2], text: args[3])
default:
  fputs("Unknown command: \(args[1])\n", stderr)
  exit(1)
}
